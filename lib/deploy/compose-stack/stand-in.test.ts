import { describe, test } from "node:test";
import assert from "node:assert/strict";

import yaml from "../../yaml";
import { standInStack, stackOverlapBlocker, stackReplicas } from "./stand-in";
import { buildDoc, route } from "./stack-test-helpers";
import type { ComposeDoc } from "./types";

const RENDERED = `# Generated by Deplo  demo
services:
  web:
    image: deplo/demo-web:abc
    build:
      context: /data/stacks/demo.src/web
    depends_on:
      api:
        condition: service_healthy
    networks:
      deplo: null
      backend:
        aliases: [front]
    labels:
      - traefik.enable=true
  api:
    image: acme/api:1
    networks: [backend, deplo]
    labels: []
  job:
    image: acme/job:1
    labels: []
networks:
  backend:
    internal: true
  deplo:
    name: deplo-env-environ_1
    external: true
volumes:
  unused: {}
`;

type Doc = ComposeDoc & { services: Record<string, Record<string, unknown>> };

describe("the stand-in of a rendered stack", () => {
  const doc = yaml.load(standInStack(RENDERED)) as Doc;

  test("every service runs under a name of its own, with what it waits for renamed too", () => {
    assert.deepEqual(Object.keys(doc.services), [
      "web_next",
      "api_next",
      "job_next",
    ]);
    assert.deepEqual(doc.services.web_next.depends_on, {
      api_next: { condition: "service_healthy" },
    });
  });

  test("the Environment's network learns no name the live stack answers to", () => {
    for (const svc of ["web_next", "api_next"])
      assert.equal(
        (doc.services[svc].networks as Record<string, unknown>).deplo,
        null,
      );
    assert.deepEqual(doc.networks?.deplo, {
      name: "deplo-env-environ_1",
      external: true,
    });
  });

  test("its own networks are a second set, where each service keeps its name", () => {
    assert.deepEqual(doc.services.web_next.networks, {
      deplo: null,
      backend: { aliases: ["front", "web"] },
    });
    assert.deepEqual(doc.services.api_next.networks, {
      backend: { aliases: ["api"] },
      deplo: null,
    });
    // Kept off the Environment's network, so it only ever had the stack's default one.
    assert.deepEqual(doc.services.job_next.networks, {
      default: { aliases: ["job"] },
    });
  });

  test("it builds nothing and declares no volume", () => {
    assert.equal(doc.services.web_next.build, undefined);
    assert.equal(doc.services.web_next.image, "deplo/demo-web:abc");
    assert.equal(doc.volumes, undefined);
  });

  test("it is marked, and keeps the header of the stack it stands in for", () => {
    assert.deepEqual(doc.services.api_next.labels, ["deplo.stand-in=true"]);
    assert.match(standInStack(RENDERED), /^# Generated by Deplo {2}demo\n/);
  });
});

describe("whether a stack can run twice", () => {
  const rendered = yaml.load(RENDERED) as ComposeDoc;
  const authored = "services:\n  web:\n    image: x\n  api:\n    image: y\n";

  test("a stack with nothing on disk and no fixed name can", () => {
    assert.equal(stackOverlapBlocker(authored, rendered), null);
  });

  test("another stack of the Environment already answering to the stand-in's name stops it", () => {
    assert.match(
      stackOverlapBlocker(authored, rendered, null, ["API_next"]) ?? "",
      /`api` starts as `api_next`, a name this environment already uses/,
    );
  });

  test("a Volume or a Bind of the app stops it, Files do not", () => {
    const vol = (type: "named" | "host" | "app") => [
      { id: "v", type, name: "data", mountPath: "/data", readOnly: false },
    ];
    for (const type of ["named", "host"] as const)
      assert.match(
        stackOverlapBlocker(authored, rendered, vol(type)) ?? "",
        /has a Volume or a Bind/,
      );
    assert.equal(stackOverlapBlocker(authored, rendered, vol("app")), null);
  });

  test("a network Deplo did not create for the stack stops it", () => {
    for (const def of [
      { external: true },
      { name: "shared" },
      { driver: "macvlan" },
    ])
      assert.match(
        stackOverlapBlocker(authored, {
          ...rendered,
          networks: { lan: def },
        }) ?? "",
        /network `lan` sets/,
      );
  });

  test("the most copies any service asks for decides", () => {
    assert.equal(stackReplicas(authored), 1);
    assert.equal(stackReplicas(null), 1);
    assert.equal(
      stackReplicas(
        "services:\n  a: {image: x, deploy: {replicas: 2}}\n  b: {image: x, deploy: {replicas: 4}}\n",
      ),
      4,
    );
  });
});

describe("the port a routed service is probed on", () => {
  const STACK = `services:
  web:
    image: nginx:1.27
    deploy:
      replicas: 2
LABELS`;
  const probe = (labels: string, extra: Parameters<typeof buildDoc>[1]) => {
    const doc = buildDoc(STACK.replace("LABELS", labels), {
      dockerVersion: "27.0.0",
      ...extra,
    });
    const hc = (
      doc.services.web as unknown as { healthcheck?: { test: string[] } }
    ).healthcheck;
    return hc?.test[1] ?? "";
  };
  // 8080 is 1F90 and 9000 is 2328 in the probe's own spelling.
  test("is the one its domain is routed to, handed over by the renderer", () => {
    assert.match(
      probe("", { domainRoutes: [route("a.example.com", "web", 8080)] }),
      /= 1F90 /,
    );
  });

  test("is the one hand-written labels name, when the App may write them", () => {
    assert.match(
      probe(
        "    labels:\n      - traefik.http.services.own.loadbalancer.server.port=9000\n",
        {
          domainRoutes: [route("a.example.com", "web", 8080)],
          allowTraefikLabels: true,
        },
      ),
      /= 2328 /,
    );
  });

  test("a service no domain reaches gets none", () => {
    assert.equal(probe("", { domainRoutes: [] }), "");
  });
});
